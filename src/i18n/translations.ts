export type TranslationKey = keyof typeof UI_TRANSLATIONS['ja'];

export function t(lang: SupportedLang, key: TranslationKey, params?: Record<string, string | number>): string {
  const dictionary = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS['ja'];
  let text = dictionary[key] || UI_TRANSLATIONS['ja'][key] || '';
  if (params) {
    Object.entries(params).forEach(([paramKey, val]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
    });
  }
  return text;
}
