/**
 * Returns a localized Spot instance given a base Spot and current language.
 */
export function getLocalizedSpot(spot: Spot, lang: SupportedLang): Spot {
  const localizedData = SPOTS_LOCALIZED[spot.id]?.[lang];
  if (!localizedData) return spot;

  return {
    ...spot,
    name: localizedData.name,
    subtitle: localizedData.subtitle,
    category: localizedData.category,
    description: localizedData.description,
    jrTip: localizedData.jrTip,
    recommendPoint: localizedData.jrTip,
    photoTip: localizedData.photoTip,
    hashtags: localizedData.hashtags,
    stampName: localizedData.stampName || spot.stampName,
    stampShort: localizedData.stampShort || spot.stampShort,
  };
}

export function getLocalizedSpots(lang: SupportedLang): Spot[] {
  return NICHINAN_SPOTS.map((s) => getLocalizedSpot(s, lang));
}
